"""Step A of the pipeline: raw + hand-compiled data -> data/processed/{data.json, regions.csv, plants.csv}.

Usage:  python src/data_prep/run_data_prep.py
"""
import sys
import warnings
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import PROCESSED, ROOT  # noqa: E402
import steps  # noqa: E402

warnings.filterwarnings("ignore", message="Unknown extension")  # openpyxl notice on the source workbook

STEPS = [steps.s1_regions, steps.s2_population, steps.s3_weather, steps.s4_grid, steps.s5_plants, steps.s6_policy]


def main():
    t0 = time.time()
    ctx = {"qa": ["# Data preparation QA report", "", "Generated by `src/data_prep/run_data_prep.py`.", ""]}
    for fn in STEPS:
        t = time.time()
        ctx = fn(ctx)
        print(f"  {fn.__name__:<16} {time.time() - t:5.1f} s")
    ctx = steps.s7_export(ctx, PROCESSED, ROOT / "outputs" / "review")
    out = ROOT / "outputs"
    out.mkdir(exist_ok=True)
    (out / "qa_report.md").write_text("\n".join(ctx["qa"]) + "\n", encoding="utf-8")
    print("\n".join(ctx["qa"][4:]))
    print(f"Data prep done in {time.time() - t0:.1f} s")


if __name__ == "__main__":
    main()
